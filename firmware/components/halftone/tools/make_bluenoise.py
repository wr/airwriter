"""Builds bluenoise64.h: a 64 x 64 blue-noise threshold mask for the halftone.

Void-and-cluster (Ulichney 1993) on a torus, so the tile repeats seamlessly.
The ImageWriter's dots are twice as tall as they are wide (144 dpi across,
72 down), so the energy filter measures distance on the paper, not in
pixels: a row apart counts double. Ranks are quantised to 256 levels, 16
pixels per level, so a level-v threshold prints exactly v/256 of a flat tint
and the firmware, the host tool and the web page can share one byte table.

    python3 firmware/components/halftone/tools/make_bluenoise.py
"""
import pathlib, numpy as np

N = 64
SIGMA = 1.9            # in dot widths, on the paper
SEED = 1984
OUT = pathlib.Path(__file__).resolve().parent.parent / "bluenoise64.h"

def filter_kernel():
    y, x = np.mgrid[0:N, 0:N]
    dx = np.minimum(x, N - x).astype(float)
    dy = np.minimum(y, N - y).astype(float) * 2.0          # rows are twice as tall
    return np.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))

K = np.fft.fft2(filter_kernel())

def energy(binary):
    return np.real(np.fft.ifft2(np.fft.fft2(binary.astype(float)) * K))

def tightest_cluster(binary):
    e = energy(binary); e[~binary] = -np.inf
    return np.unravel_index(np.argmax(e), e.shape)

def largest_void(binary):
    e = energy(binary); e[binary] = np.inf
    return np.unravel_index(np.argmin(e), e.shape)

def initial_pattern(rng):
    binary = np.zeros((N, N), bool)
    ones = rng.choice(N * N, N * N // 10, replace=False)
    binary.flat[ones] = True
    while True:
        c = tightest_cluster(binary); binary[c] = False
        v = largest_void(binary);     binary[v] = True
        if v == c: break
    return binary

def main():
    rng = np.random.default_rng(SEED)
    proto = initial_pattern(rng)
    rank = np.zeros((N, N), int)
    # phase 1: remove the tightest clusters, numbering down
    binary = proto.copy(); ones = int(binary.sum())
    for r in range(ones - 1, -1, -1):
        c = tightest_cluster(binary); binary[c] = False; rank[c] = r
    # phase 2: fill the largest voids, numbering up to half
    binary = proto.copy()
    for r in range(ones, N * N // 2):
        v = largest_void(binary); binary[v] = True; rank[v] = r
    # phase 3: now the clusters are of zeros; fill the tightest, numbering on
    for r in range(N * N // 2, N * N):
        c = tightest_cluster(~binary); binary[c] = True; rank[c] = r
    assert sorted(rank.flat) == list(range(N * N))
    level = rank // (N * N // 256)
    assert all(int((level == v).sum()) == 16 for v in range(256))
    lines = ["// SPDX-License-Identifier: GPL-3.0-or-later",
             "// Generated by tools/make_bluenoise.py; do not edit.",
             "// 64 x 64 blue-noise thresholds, 0..255, 16 pixels per level, row-major.",
             "static const uint8_t bluenoise64[64 * 64] = {"]
    for row in level:
        lines.append("    " + ",".join("%3d" % v for v in row) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)

if __name__ == "__main__":
    main()
