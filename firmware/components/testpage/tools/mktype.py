"""Builds the test page's type tester (W-1140): a sans and a serif at five sizes, two columns
across the page's 8 in, as 1-bit rows at 720 dpi, deflated, in tp_type.h.

The board makes the tester's rows at its page's own dots from these, as it makes a phone's
page: averaged down (resample.h, so the letters' edges come out gray, as a phone draws them)
and screened with the screen in use. The size labels are the page's own face, drawn by the
page; this draws only the samples, each line the longest run of whole words that fits.

The faces are TeX Gyre Heros and TeX Gyre Termes (GUST Font License, LICENSE.md), free
copies of Helvetica and Times, from CTAN's fonts/tex-gyre/opentype. They are not kept in the
repository: put them in ~/.config/airwriter/type-fonts/ or name them. Needs Pillow and numpy
(python3.14 here):

    python3.14 firmware/components/testpage/tools/mktype.py [--sans FONT] [--serif FONT]
"""
import argparse, pathlib, zlib

import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "../tp_type.h"
FONTS = pathlib.Path.home() / ".config/airwriter/type-fonts"

DPI = 720
W = 8 * DPI                       # the page's 8 in
SIZES = (6, 8, 10, 12, 18)        # points
LEAD = 1.25                       # a line's height, in ems
BASE = 0.95                       # its baseline from its top, in ems
COL_X = (0, 41 * DPI // 10)        # each column's left: its size labels
SAMPLE_DX = DPI // 2               # from a label to its sample
COL_W = 39 * DPI // 10 - SAMPLE_DX
TEXT = "The quick brown fox jumps over the lazy dog 0123456789"


def font(spec, px):
    path, _, idx = spec.partition(":")
    return ImageFont.truetype(path, size=px, index=int(idx or 0))


def fit(f, text, w):
    words = text.split()
    while words and f.getlength(" ".join(words)) > w:
        words.pop()
    return " ".join(words)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sans", default=str(FONTS / "texgyreheros-regular.otf"))
    ap.add_argument("--serif", default=str(FONTS / "texgyretermes-regular.otf"))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()

    tops, bases, y = [], [], 0
    for pt in SIZES:
        em = pt * DPI / 72
        tops.append(y)
        bases.append(y + round(BASE * em))
        y += round(LEAD * em)
    h = y
    im = Image.new("L", (W, h), 255)
    d = ImageDraw.Draw(im)
    for col, spec in enumerate((a.sans, a.serif)):
        for pt, base in zip(SIZES, bases):
            f = font(spec, round(pt * DPI / 72))
            s = fit(f, TEXT, COL_W)
            d.text((COL_X[col] + SAMPLE_DX, base), s, font=f, fill=0, anchor="ls")
    bits = np.packbits(np.asarray(im) < 128, axis=1)
    z = zlib.compress(bits.tobytes(), 9)

    out = []
    out.append("// SPDX-License-Identifier: GPL-3.0-or-later")
    out.append("//")
    out.append("// Generated by firmware/components/testpage/tools/mktype.py: do not edit. The test page's")
    out.append("// type tester (W-1140), TeX Gyre Heros and Termes (GUST Font License, LICENSE.md) at five")
    out.append("// sizes: 1-bit rows at %d dpi, MSB first, (TP_TYPE_W + 7) / 8 bytes a row, deflated" % DPI)
    out.append("// (tp_unpack.h). A line's baseline is tp_type_base rows down; its size label goes at")
    out.append("// tp_type_col_x, its sample TP_TYPE_SAMPLE_DX right of that, both at %d dpi." % DPI)
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("#define TP_TYPE_DPI       %d" % DPI)
    out.append("#define TP_TYPE_W         %d" % W)
    out.append("#define TP_TYPE_H         %d" % h)
    out.append("#define TP_TYPE_LINES     %d" % len(SIZES))
    out.append("#define TP_TYPE_SAMPLE_DX %d" % SAMPLE_DX)
    out.append("static const uint16_t tp_type_col_x[2] = { %d, %d };" % COL_X)
    out.append("static const uint8_t  tp_type_pt[TP_TYPE_LINES] = { %s };" % ", ".join(map(str, SIZES)))
    out.append("static const uint16_t tp_type_base[TP_TYPE_LINES] = { %s };" % ", ".join(map(str, bases)))
    out.append("static const uint8_t tp_type_z[%d] = {" % len(z))
    for i in range(0, len(z), 16):
        out.append("    " + ", ".join("0x%02x" % b for b in z[i:i + 16]) + ",")
    out.append("};")
    pathlib.Path(a.out).write_text("\n".join(out) + "\n")
    print("%s: %d x %d, %d bytes deflated" % (pathlib.Path(a.out).name, W, h, len(z)))


if __name__ == "__main__":
    main()
