// mkscene: writes firmware/components/stylewriter/sw_scene.h, the StyleWriter test page's
// pictures traced once here rather than on the board while it prints (W-1133). Tracing them
// there took longer than sending them, and the printer stopped partway down the page to wait.
// The still life is stored as tp_scene.c draws it at 180 dpi, RGB; the screen panels as the
// same scene in gray through ink_gray, as sw_testpage.c screened it. Each is a zlib stream that
// sw_unpack.h reads a row at a time.
//
//     make -C tools/rip scene
//
// after any change to tp_scene.c, ink_gray or the sizes below (sw_testpage.c holds its own
// sizes to these). test_sw_testpage.c fails when the stored pictures and tp_scene.c disagree.
#include "tp_scene.h"
#include "ink.h"

#include <stdio.h>
#include <stdlib.h>
#include <zlib.h>

#define SCENE_W 632u                // the still life: PHOTO_W / 2, PHOTO_H / 2 in sw_testpage.c
#define SCENE_H 350u
#define PANEL_W 400u                // a screen panel
#define PANEL_H 300u

static unsigned char *deflated(const unsigned char *raw, size_t n, size_t *zn)
{
    uLongf cap = compressBound(n);
    unsigned char *z = malloc(cap);
    if (!z || compress2(z, &cap, raw, n, 9) != Z_OK) {
        fprintf(stderr, "mkscene: no memory to deflate\n");
        exit(1);
    }
    *zn = cap;
    return z;
}

static void array(FILE *f, const char *name, const unsigned char *z, size_t n)
{
    fprintf(f, "static const uint8_t %s[%zu] = {", name, n);
    for (size_t i = 0; i < n; i++) fprintf(f, "%s0x%02x,", i % 16 ? " " : "\n    ", z[i]);
    fprintf(f, "\n};\n");
}

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: mkscene OUT.h\n");
        return 2;
    }
    size_t pn = (size_t)SCENE_W * SCENE_H * 3, gn = (size_t)PANEL_W * PANEL_H;
    unsigned char *photo = malloc(pn), *panel = malloc(gn), *rgb = malloc((size_t)PANEL_W * 3);
    if (!photo || !panel || !rgb) return 1;
    for (uint32_t y = 0; y < SCENE_H; y++)
        tp_scene_row_aspect(SCENE_W, SCENE_H, y, photo + (size_t)y * SCENE_W * 3, (float)SCENE_H / SCENE_W);
    for (uint32_t y = 0; y < PANEL_H; y++) {
        tp_scene_row_aspect(PANEL_W, PANEL_H, y, rgb, (float)PANEL_H / PANEL_W);
        ink_gray(rgb, PANEL_W, panel + (size_t)y * PANEL_W);
    }
    size_t pz, gz;
    unsigned char *photo_z = deflated(photo, pn, &pz), *panel_z = deflated(panel, gn, &gz);

    FILE *f = fopen(argv[1], "w");
    if (!f) {
        perror(argv[1]);
        return 1;
    }
    fprintf(f, "// SPDX-License-Identifier: GPL-3.0-or-later\n"
               "//\n"
               "// Generated by tools/rip/mkscene.c (make -C tools/rip scene) from testpage/tp_scene.c.\n"
               "// Do not edit. The StyleWriter test page's still life, %u x %u RGB at 180 dpi, and\n"
               "// the scene its screen panels show, %u x %u gray; each a zlib stream (sw_unpack.h).\n"
               "#pragma once\n#include <stdint.h>\n\n"
               "#define SW_SCENE_W %uu\n#define SW_SCENE_H %uu\n#define SW_PANEL_W %uu\n#define SW_PANEL_H %uu\n\n",
            SCENE_W, SCENE_H, PANEL_W, PANEL_H, SCENE_W, SCENE_H, PANEL_W, PANEL_H);
    array(f, "sw_scene_photo_z", photo_z, pz);
    fprintf(f, "\n");
    array(f, "sw_scene_panel_z", panel_z, gz);
    fclose(f);
    printf("mkscene: %s, still life %zu bytes, panels %zu bytes\n", argv[1], pz, gz);
    free(photo); free(panel); free(rgb); free(photo_z); free(panel_z);
    return 0;
}
