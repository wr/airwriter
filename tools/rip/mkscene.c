// mkscene: writes firmware/components/testpage/tp_pictures.h, the test page's picture traced
// once here rather than on the board while it prints (W-1133). Tracing it there took longer
// than sending it, and the printer stopped partway down the page to wait. The still life the
// screen panels show is stored as tp_scene.c draws it, in gray through ink_gray, as a zlib
// stream that tp_unpack.h reads a row at a time.
//
//     make -C tools/rip scene
//
// after any change to tp_scene.c, ink_gray or the sizes below (testpage.c holds its own sizes
// to these). test_testpage.c fails when the stored picture and tp_scene.c disagree.
#include "tp_scene.h"
#include "ink.h"

#include <stdio.h>
#include <stdlib.h>
#include <zlib.h>

#define PANEL_W 400u                // a screen panel, at 360 dpi
#define PANEL_H 300u

static unsigned char *deflated(const unsigned char *raw, size_t n, size_t *zn)
{
    uLongf cap = compressBound(n);
    unsigned char *z = malloc(cap);
    if (!z || compress2(z, &cap, raw, n, 9) != Z_OK) {
        fprintf(stderr, "mkscene: no memory to deflate\n");
        exit(1);
    }
    *zn = cap;
    return z;
}

static void array(FILE *f, const char *name, const unsigned char *z, size_t n)
{
    fprintf(f, "static const uint8_t %s[%zu] = {", name, n);
    for (size_t i = 0; i < n; i++) fprintf(f, "%s0x%02x,", i % 16 ? " " : "\n    ", z[i]);
    fprintf(f, "\n};\n");
}

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: mkscene OUT.h\n");
        return 2;
    }
    size_t gn = (size_t)PANEL_W * PANEL_H;
    unsigned char *panel = malloc(gn), *rgb = malloc((size_t)PANEL_W * 3);
    if (!panel || !rgb) return 1;
    for (uint32_t y = 0; y < PANEL_H; y++) {
        tp_scene_row_aspect(PANEL_W, PANEL_H, y, rgb, (float)PANEL_H / PANEL_W);
        ink_gray(rgb, PANEL_W, panel + (size_t)y * PANEL_W);
    }
    size_t gz;
    unsigned char *panel_z = deflated(panel, gn, &gz);

    FILE *f = fopen(argv[1], "w");
    if (!f) {
        perror(argv[1]);
        return 1;
    }
    fprintf(f, "// SPDX-License-Identifier: GPL-3.0-or-later\n"
               "//\n"
               "// Generated by tools/rip/mkscene.c (make -C tools/rip scene) from testpage/tp_scene.c.\n"
               "// Do not edit. The test page's still life as its screen panels show it, %u x %u\n"
               "// gray at 360 dpi, a zlib stream (tp_unpack.h).\n"
               "#pragma once\n#include <stdint.h>\n\n"
               "#define TP_PANEL_W %uu\n#define TP_PANEL_H %uu\n\n",
            PANEL_W, PANEL_H, PANEL_W, PANEL_H);
    array(f, "tp_panel_z", panel_z, gz);
    fclose(f);
    printf("mkscene: %s, %zu bytes\n", argv[1], gz);
    free(panel); free(rgb); free(panel_z);
    return 0;
}
